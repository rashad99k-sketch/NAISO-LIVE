"""PostgreSQL-backed implementation of the GGP TradeJournal contract.

This adapter is opt-in via TRADE_JOURNAL_BACKEND=postgres. It intentionally
keeps the SQLite adapter available for local development and migration rehearsal.
No exchange/network trading calls are made by this module.
"""
from __future__ import annotations

import json
import os
import time
from typing import Any, Dict, Iterable, Optional

try:
    import psycopg
    from psycopg import sql
    from psycopg.rows import dict_row
except Exception as exc:  # pragma: no cover - exercised by deployment diagnostics
    psycopg = None
    sql = None
    dict_row = None
    _PSYCOPG_IMPORT_ERROR = exc
else:
    _PSYCOPG_IMPORT_ERROR = None


_SCHEMA_VERSION = 1
_COLUMNS = """
trade_id TEXT PRIMARY KEY,
symbol TEXT NOT NULL,
side TEXT NOT NULL,
setup_type TEXT,
status TEXT NOT NULL,
entry_ts DOUBLE PRECISION,
entry_qty DOUBLE PRECISION,
entry_price DOUBLE PRECISION,
sl_price DOUBLE PRECISION,
native_sl_order_id TEXT,
tp1_hit BOOLEAN NOT NULL DEFAULT FALSE,
tp2_hit BOOLEAN NOT NULL DEFAULT FALSE,
remaining_qty DOUBLE PRECISION,
close_ts DOUBLE PRECISION,
close_price DOUBLE PRECISION,
close_reason TEXT,
close_confidence TEXT,
realized_pnl DOUBLE PRECISION,
finalized BOOLEAN NOT NULL DEFAULT FALSE,
actual_filled_qty DOUBLE PRECISION,
tp1_filled_qty DOUBLE PRECISION DEFAULT 0,
tp1_execution_price DOUBLE PRECISION,
tp2_filled_qty DOUBLE PRECISION DEFAULT 0,
trailing_state TEXT,
highest_favorable DOUBLE PRECISION,
lowest_favorable DOUBLE PRECISION,
mfe DOUBLE PRECISION,
profit_mode TEXT,
exchange_state TEXT,
pending_orders TEXT,
last_reconciled_ts DOUBLE PRECISION,
lifecycle_state TEXT,
state_json TEXT,
updated_ts DOUBLE PRECISION,
client_order_id TEXT,
exchange_order_id TEXT,
position_mode TEXT,
position_side TEXT,
leverage DOUBLE PRECISION,
requested_qty DOUBLE PRECISION,
average_fill_price DOUBLE PRECISION,
actual_entry_price DOUBLE PRECISION,
initial_sl DOUBLE PRECISION,
recovery_status TEXT,
close_evidence TEXT,
event_ids TEXT,
tp1_price DOUBLE PRECISION,
tp2_price DOUBLE PRECISION,
native_sl_verified BOOLEAN NOT NULL DEFAULT FALSE,
native_sl_status TEXT
"""


class PostgresTradeJournal:
    """Drop-in journal API with explicit transactions and bounded DB timeouts."""

    def __init__(self, dsn: Optional[str] = None, *, connect_timeout: Optional[int] = None,
                 statement_timeout_ms: Optional[int] = None):
        if psycopg is None:
            raise RuntimeError(
                "psycopg 3 is required for PostgreSQL journal"
            ) from _PSYCOPG_IMPORT_ERROR
        self.dsn = (dsn or os.getenv("DATABASE_URL") or "").strip()
        if not self.dsn:
            raise RuntimeError("DATABASE_URL is required when TRADE_JOURNAL_BACKEND=postgres")
        self.connect_timeout = int(connect_timeout or os.getenv("DB_CONNECT_TIMEOUT_SEC", "5"))
        self.statement_timeout_ms = int(statement_timeout_ms or os.getenv("DB_STATEMENT_TIMEOUT_MS", "8000"))
        if self.connect_timeout < 1 or self.statement_timeout_ms < 100:
            raise ValueError("database timeouts are outside safe bounds")
        self._init_schema()

    def _db(self):
        # psycopg connection context commits on success, rolls back on exception,
        # and closes the connection. TLS is required by the managed DB URI.
        return psycopg.connect(
            self.dsn,
            connect_timeout=self.connect_timeout,
            row_factory=dict_row,
            options=f"-c statement_timeout={self.statement_timeout_ms}",
        )

    @staticmethod
    def _json(value: Any) -> str:
        return json.dumps(value, sort_keys=True, default=str, separators=(",", ":"))

    @staticmethod
    def _decode_row(row: Optional[Dict[str, Any]]) -> Optional[Dict[str, Any]]:
        if row is None:
            return None
        result = dict(row)
        for raw_key, parsed_key, default in (
            ("state_json", "state", "{}"),
            ("trailing_state", "trailing_state_data", "{}"),
            ("pending_orders", "pending_orders_data", "[]"),
        ):
            try:
                result[parsed_key] = json.loads(result.get(raw_key) or default)
            except (TypeError, ValueError):
                result[parsed_key] = {} if default == "{}" else []
        return result

    def _init_schema(self) -> None:
        with self._db() as db:
            db.execute(f"CREATE TABLE IF NOT EXISTS trades ({_COLUMNS})")
            db.execute("""
                CREATE TABLE IF NOT EXISTS trade_events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    trade_id TEXT NOT NULL,
                    event_key TEXT NOT NULL,
                    event_type TEXT NOT NULL,
                    payload TEXT,
                    created_ts DOUBLE PRECISION NOT NULL,
                    CONSTRAINT uq_trade_events_key UNIQUE (trade_id, event_key)
                )
            """)
            db.execute("""
                CREATE TABLE IF NOT EXISTS consumed_events (
                    event_id TEXT PRIMARY KEY,
                    trade_id TEXT NOT NULL,
                    created_ts DOUBLE PRECISION NOT NULL
                )
            """)
            db.execute("""
                CREATE TABLE IF NOT EXISTS trade_journal_schema_migrations (
                    version INTEGER PRIMARY KEY,
                    applied_ts DOUBLE PRECISION NOT NULL
                )
            """)
            db.execute("""
                CREATE UNIQUE INDEX IF NOT EXISTS ux_trades_client_order_id
                ON trades(client_order_id) WHERE client_order_id IS NOT NULL
            """)
            db.execute("CREATE INDEX IF NOT EXISTS ix_trade_events_trade ON trade_events(trade_id)")
            db.execute(
                "INSERT INTO trade_journal_schema_migrations(version, applied_ts) "
                "VALUES (%s, %s) ON CONFLICT(version) DO NOTHING",
                (_SCHEMA_VERSION, time.time()),
            )

    def health_check(self) -> Dict[str, Any]:
        with self._db() as db:
            row = db.execute("""
                SELECT current_database() AS database,
                       current_user AS db_user,
                       (SELECT MAX(version) FROM trade_journal_schema_migrations) AS schema_version
            """).fetchone()
            db.execute("SELECT 1").fetchone()
        return {"ok": True, "schema_version": int(row["schema_version"] or 0)}

    def persist_entry_pending(self, *, trade_id: str, client_order_id: str, symbol: str,
                              side: str, position_mode: str, position_side: str,
                              leverage: float, requested_qty: float, entry_ts: float,
                              status: str = "ENTRY_PENDING", **extra: Any) -> None:
        management_state = extra.get("management_state")
        state_json = self._json(management_state) if isinstance(management_state, dict) else None
        initial_sl = extra.get("structural_stop")
        tp1_price = management_state.get("tp1_price") if isinstance(management_state, dict) else None
        tp2_price = management_state.get("tp2_price") if isinstance(management_state, dict) else None
        with self._db() as db:
            db.execute("""
                INSERT INTO trades(
                    trade_id,symbol,side,status,entry_ts,entry_qty,remaining_qty,actual_filled_qty,
                    client_order_id,position_mode,position_side,leverage,requested_qty,recovery_status,
                    sl_price,initial_sl,state_json,updated_ts,tp1_price,tp2_price
                ) VALUES (%s,%s,%s,%s,%s,%s,0,0,%s,%s,%s,%s,%s,'ENTRY_PENDING',
                          %s,%s,%s,%s,%s,%s)
                ON CONFLICT(trade_id) DO UPDATE SET
                    status=EXCLUDED.status,
                    client_order_id=EXCLUDED.client_order_id,
                    position_mode=EXCLUDED.position_mode,
                    position_side=EXCLUDED.position_side,
                    leverage=EXCLUDED.leverage,
                    requested_qty=EXCLUDED.requested_qty,
                    sl_price=COALESCE(EXCLUDED.sl_price,trades.sl_price),
                    initial_sl=COALESCE(EXCLUDED.initial_sl,trades.initial_sl),
                    tp1_price=COALESCE(EXCLUDED.tp1_price,trades.tp1_price),
                    tp2_price=COALESCE(EXCLUDED.tp2_price,trades.tp2_price),
                    state_json=COALESCE(EXCLUDED.state_json,trades.state_json),
                    updated_ts=EXCLUDED.updated_ts
            """, (str(trade_id), str(symbol), str(side), str(status), float(entry_ts),
                  float(requested_qty), str(client_order_id), str(position_mode),
                  str(position_side), float(leverage), float(requested_qty),
                  initial_sl, initial_sl, state_json, time.time(), tp1_price, tp2_price))
            self.event(str(trade_id), f"entry-pending:{client_order_id}", "ENTRY_PENDING", {
                "client_order_id": str(client_order_id), "symbol": str(symbol),
                "requested_qty": float(requested_qty), "structural_stop": initial_sl,
                "tp1_price": tp1_price, "tp2_price": tp2_price,
                "management_state_persisted": bool(state_json),
            }, db=db)

    def record_execution(self, trade_id: str, *, exchange_order_id: Optional[str],
                         filled_qty: float, remaining_qty: float,
                         average_fill_price: Optional[float], actual_entry_price: Optional[float],
                         status: str, recovery_status: str = "") -> None:
        with self._db() as db:
            row = db.execute(
                "SELECT state_json,entry_qty,entry_price FROM trades WHERE trade_id=%s FOR UPDATE",
                (str(trade_id),),
            ).fetchone()
            state = {}
            if row and row.get("state_json"):
                try:
                    parsed = json.loads(row["state_json"])
                    state = parsed if isinstance(parsed, dict) else {}
                except (TypeError, ValueError):
                    pass
            filled = max(0.0, float(filled_qty or 0.0))
            remaining = max(0.0, float(remaining_qty or 0.0))
            entry = actual_entry_price if actual_entry_price is not None else average_fill_price
            if filled > 0:
                state.update({"actual_filled_qty": filled, "initial_qty": filled,
                              "qty": filled, "remaining_qty": filled,
                              "exchange_qty": filled, "order_remaining_qty": remaining})
            else:
                state["order_remaining_qty"] = remaining
            if entry is not None and float(entry) > 0:
                state["entry"] = float(entry)
            state.update({"trade_id": str(trade_id), "entry_execution_state": str(status),
                          "exchange_order_id": exchange_order_id})
            db.execute("""
                UPDATE trades SET exchange_order_id=%s,
                    actual_filled_qty=CASE WHEN %s>0 THEN %s ELSE actual_filled_qty END,
                    entry_qty=CASE WHEN %s>0 THEN %s ELSE entry_qty END,
                    remaining_qty=CASE WHEN %s>0 THEN %s ELSE remaining_qty END,
                    average_fill_price=%s, actual_entry_price=%s,
                    entry_price=COALESCE(%s,entry_price), status=%s, recovery_status=%s,
                    state_json=%s, updated_ts=%s WHERE trade_id=%s
            """, (exchange_order_id, filled, filled, filled, filled, filled, filled,
                  average_fill_price, actual_entry_price, entry, str(status), str(recovery_status),
                  self._json(state), time.time(), str(trade_id)))
            self.event(str(trade_id), f"execution:{status}:{exchange_order_id or 'unknown'}",
                       "EXECUTION_VERIFIED", {"status": str(status), "filled_qty": filled,
                       "remaining_qty": remaining, "average_fill_price": average_fill_price}, db=db)

    def start_trade(self, trade_id: str, symbol: str, side: str, setup_type: str,
                    qty: float, entry_price: float, sl_price: Optional[float] = None) -> None:
        with self._db() as db:
            db.execute("""
                INSERT INTO trades(trade_id,symbol,side,setup_type,status,entry_ts,entry_qty,
                    entry_price,sl_price,remaining_qty,actual_filled_qty,updated_ts)
                VALUES(%s,%s,%s,%s,'OPEN',%s,%s,%s,%s,%s,%s,%s)
                ON CONFLICT(trade_id) DO UPDATE SET
                    symbol=EXCLUDED.symbol, side=EXCLUDED.side,
                    setup_type=COALESCE(EXCLUDED.setup_type,trades.setup_type),
                    status=CASE WHEN trades.finalized=FALSE THEN 'OPEN' ELSE trades.status END,
                    entry_ts=COALESCE(trades.entry_ts,EXCLUDED.entry_ts),
                    entry_qty=COALESCE(NULLIF(trades.actual_filled_qty,0),EXCLUDED.entry_qty,trades.entry_qty),
                    entry_price=COALESCE(EXCLUDED.entry_price,trades.entry_price),
                    sl_price=COALESCE(EXCLUDED.sl_price,trades.sl_price),
                    remaining_qty=COALESCE(trades.remaining_qty,EXCLUDED.remaining_qty),
                    actual_filled_qty=COALESCE(NULLIF(trades.actual_filled_qty,0),EXCLUDED.actual_filled_qty),
                    updated_ts=EXCLUDED.updated_ts
            """, (str(trade_id), str(symbol), str(side), setup_type, time.time(),
                  float(qty), float(entry_price), sl_price, float(qty), float(qty), time.time()))
            self.event(trade_id, "trade_started", "TRADE_STARTED",
                       {"qty": qty, "entry_price": entry_price}, db=db)

    def update(self, trade_id: str, **fields: Any) -> None:
        allowed = {
            "status", "recovery_status", "native_sl_order_id", "native_sl_verified",
            "native_sl_status", "tp1_hit", "tp2_hit", "remaining_qty", "close_ts",
            "close_price", "close_reason", "close_confidence", "realized_pnl",
            "actual_filled_qty", "tp1_filled_qty", "tp1_execution_price", "tp2_filled_qty",
            "trailing_state", "highest_favorable", "lowest_favorable", "mfe", "profit_mode",
            "exchange_state", "pending_orders", "last_reconciled_ts", "lifecycle_state",
            "position_mode", "position_side", "entry_price", "entry_qty", "tp1_price", "tp2_price",
        }
        values = [(key, self._json(value) if key in {"trailing_state", "pending_orders"} and value is not None else value)
                  for key, value in fields.items() if key in allowed]
        if not values:
            return
        assignments = sql.SQL(", ").join(
            sql.SQL("{} = %s").format(sql.Identifier(key)) for key, _ in values
        )
        with self._db() as db:
            db.execute(
                sql.SQL("UPDATE trades SET {}, updated_ts = %s WHERE trade_id = %s").format(assignments),
                [value for _, value in values] + [time.time(), str(trade_id)],
            )

    def save_snapshot(self, trade_id: str, state: Dict[str, Any], event_key: Optional[str] = None,
                      event_type: str = "STATE_SNAPSHOT") -> bool:
        if not trade_id:
            return False
        val = lambda key, default=None: state.get(key, default)
        with self._db() as db:
            cur = db.execute("""
                UPDATE trades SET state_json=%s,status=%s,remaining_qty=%s,actual_filled_qty=%s,
                    entry_qty=COALESCE(%s,entry_qty),entry_price=COALESCE(%s,entry_price),
                    sl_price=COALESCE(%s,sl_price),tp1_price=COALESCE(%s,tp1_price),
                    tp2_price=COALESCE(%s,tp2_price),position_mode=COALESCE(%s,position_mode),
                    position_side=COALESCE(%s,position_side),
                    native_sl_order_id=COALESCE(%s,native_sl_order_id),
                    native_sl_verified=%s,native_sl_status=%s,tp1_hit=%s,tp1_filled_qty=%s,
                    tp1_execution_price=%s,tp2_hit=%s,tp2_filled_qty=%s,trailing_state=%s,
                    highest_favorable=%s,lowest_favorable=%s,mfe=%s,profit_mode=%s,
                    exchange_state=%s,pending_orders=%s,last_reconciled_ts=%s,
                    lifecycle_state=%s,updated_ts=%s WHERE trade_id=%s
            """, (self._json(state), str(val("trade_lifecycle_state", val("status", "OPEN"))),
                  val("remaining_qty", val("qty")), val("actual_filled_qty", val("initial_qty", val("qty"))),
                  val("initial_qty", val("qty")), val("entry"), 
                  val("native_sl_original_price", val("synthetic_sl", val("sl"))),
                  val("tp1_price", val("synthetic_tp1")), val("tp2_price"),
                  val("position_mode"), val("position_side"), val("native_sl_order_id"),
                  bool(val("native_sl_verified", False)), val("native_sl_status"),
                  bool(val("tp1_hit", False)), val("tp1_filled_qty", 0), val("tp1_execution_price"),
                  bool(val("tp2_hit", False)), val("tp2_filled_qty", 0),
                  self._json({k: val(k) for k in ("trail_activated", "trail_on", "trail_stop",
                      "profit_lock_activated", "be_done", "synthetic_sl")}),
                  val("max_price", val("peak_price")), val("min_price"), val("peak_roe"),
                  val("profit_mode"), val("exchange_state", "UNKNOWN"),
                  self._json(val("pending_orders", [])), val("last_reconciled_ts"),
                  val("trade_lifecycle_state"), time.time(), str(trade_id)))
            if cur.rowcount == 0:
                raise RuntimeError(f"cannot snapshot unknown trade_id={trade_id}")
            return self.event(trade_id, event_key or f"snapshot:{int(time.time()*1000)}",
                              event_type, {"status": val("status", "OPEN"),
                              "native_sl_verified": bool(val("native_sl_verified", False))}, db=db)

    def event(self, trade_id: str, event_key: str, event_type: str,
              payload: Optional[Dict[str, Any]] = None, db=None) -> bool:
        if db is None:
            with self._db() as conn:
                return self.event(trade_id, event_key, event_type, payload, db=conn)
        cur = db.execute("""
            INSERT INTO trade_events(trade_id,event_key,event_type,payload,created_ts)
            VALUES(%s,%s,%s,%s,%s) ON CONFLICT(trade_id,event_key) DO NOTHING
        """, (str(trade_id), str(event_key), str(event_type), self._json(payload or {}), time.time()))
        return cur.rowcount == 1

    def finalize_once(self, trade_id: str, close_reason: str, close_price: Optional[float],
                      realized_pnl: Optional[float], confidence: str = "EXCHANGE_CONFIRMED") -> bool:
        with self._db() as db:
            cur = db.execute("""
                UPDATE trades SET status='CLOSED',close_ts=%s,close_price=%s,close_reason=%s,
                    close_confidence=%s,realized_pnl=%s,finalized=TRUE,remaining_qty=0,updated_ts=%s
                WHERE trade_id=%s AND finalized=FALSE
            """, (time.time(), close_price, close_reason, confidence, realized_pnl,
                  time.time(), str(trade_id)))
            if cur.rowcount != 1:
                return False
            self.event(trade_id, "finalized", "TRADE_FINALIZED",
                       {"reason": close_reason, "confidence": confidence}, db=db)
            return True

    def is_event_consumed(self, event_id: str) -> bool:
        if not event_id:
            return False
        with self._db() as db:
            return db.execute("SELECT 1 FROM consumed_events WHERE event_id=%s",
                              (str(event_id),)).fetchone() is not None

    def consume_event(self, event_id: str, trade_id: str) -> bool:
        if not event_id or not trade_id:
            return False
        with self._db() as db:
            cur = db.execute("""
                INSERT INTO consumed_events(event_id,trade_id,created_ts)
                VALUES(%s,%s,%s) ON CONFLICT(event_id) DO NOTHING
            """, (str(event_id), str(trade_id), time.time()))
            if cur.rowcount == 1:
                self.event(str(trade_id), f"entry-event:{event_id}", "ENTRY_EVENT_CONSUMED",
                           {"event_id": str(event_id)}, db=db)
            return cur.rowcount == 1

    def get(self, trade_id: str) -> Optional[Dict[str, Any]]:
        with self._db() as db:
            row = db.execute("SELECT * FROM trades WHERE trade_id=%s", (str(trade_id),)).fetchone()
        return self._decode_row(row)

    def open_trades(self) -> Iterable[Dict[str, Any]]:
        with self._db() as db:
            rows = db.execute("SELECT * FROM trades WHERE finalized=FALSE ORDER BY entry_ts").fetchall()
        return [self._decode_row(row) for row in rows]
